"""
Trail Plant Guardian: Streamlit demo.
Run from the project folder:  streamlit run app.py
Needs pipeline.py, incident_log.py, plant_classifier.pth, classes.json, knowledge_graph.pkl alongside.
"""
import pandas as pd
import streamlit as st
from PIL import Image

import incident_log as il
import pipeline as p

st.set_page_config(page_title="Trail Plant Guardian", page_icon="🦋", layout="wide")


@st.cache_resource
def resources():
    model, classes, G = p.load_all()
    return classes, G, p.hosts_dict(G)


classes, G, HOSTS = resources()
il.init_db()

# ---------------------------------------------------------------- sidebar
with st.sidebar:
    st.header("Settings")
    use_llm = st.toggle("Use local LLM (Ollama)", value=False,
                        help="Off = fixed template text. On = Ollama llama3.2 if running, else template.")
    show_demo = st.toggle("Include simulated demo incidents", value=True)
    c1, c2 = st.columns(2)
    if c1.button("Add demo data"):
        il.seed_demo(classes, n=60)
        st.rerun()
    if c2.button("Clear demo"):
        il.clear_demo()
        st.rerun()
    st.caption(f"Confidence tiers: high ≥ {p.HIGH}, medium ≥ {p.LOW}, else low. "
               "Impact levels use damage reports in the last "
               f"{il.WINDOW_DAYS} days (Watch ≥ {il.WATCH_N}, High ≥ {il.HIGH_N}); "
               "these cutoffs are arbitrary defaults.")

st.title("🦋 Trail Plant Guardian")
st.caption("Identify a host plant, see which butterflies are recorded as using it, and log trail incidents.")

tab_report, tab_map = st.tabs(["Report a plant", "High-impact zones"])

# ---------------------------------------------------------------- report tab
with tab_report:
    zones = il.ZONES
    zlabel = {r.zone_id: f"{r.trail} – {r.zone_name}" for r in zones.itertuples()}
    left, right = st.columns([1, 1.2])

    with left:
        zone_id = st.selectbox("Trail zone", list(zlabel), format_func=zlabel.get)
        up = st.file_uploader("Photo of the plant", type=["jpg", "jpeg", "png"])
        if up:
            st.image(Image.open(up), use_container_width=True)

    with right:
        if not up:
            st.info("Upload a photo to begin.")
        else:
            res = p.advise_inputs(Image.open(up))
            tier, top3 = res["tier"], res["top3"]
            st.subheader("Identification")
            st.dataframe(pd.DataFrame(top3, columns=["Species", "Probability"])
                         .style.format({"Probability": "{:.1%}"}), hide_index=True)

            species = None
            if tier == "high":
                species = top3[0][0]
                st.success(f"High confidence: **{species}** ({top3[0][1]:.0%})")
            elif tier == "medium":
                st.warning("Medium confidence. Please confirm the species.")
                species = st.radio("Which of these is it?", [n for n, _ in top3], index=0)
            else:
                st.error("Low confidence. Retake the photo (leaves and flowers, good light), "
                         "or pick the species yourself.")
                if st.checkbox("I'll pick the species manually"):
                    species = st.selectbox("Species", sorted(classes))

            if species:
                key = (species, use_llm)
                if st.session_state.get("adv_key") != key:
                    st.session_state["adv_key"] = key
                    st.session_state["adv"] = p.advisory_for_species(species, use_llm)
                text, source = st.session_state["adv"]
                st.subheader("Advisory")
                st.write(text)
                st.caption("Generated by the local LLM from graph facts." if source == "llm"
                           else "Template text built directly from graph facts.")
                fact = p.retrieve(G, species)
                if source == "llm":
                    leaks = p.grounded(text, fact)
                    if leaks:
                        st.warning(f"Check wording, names not in the graph: {', '.join(leaks)}")
                with st.expander("Facts used"):
                    st.json(fact)

                st.divider()
                damaged = st.checkbox("I can see trampling or damage on this plant")
                if st.button("Log this incident", type="primary"):
                    il.log_incident(zone_id, species, damaged, predicted=top3[0][0],
                                    confidence=round(top3[0][1], 3), tier=tier,
                                    image_name=up.name)
                    st.success(f"Logged for {zlabel[zone_id]}. Thank you.")

# ---------------------------------------------------------------- map tab
with tab_map:
    df = il.load_incidents(include_demo=show_demo)
    summ = il.zone_summary(df, hosts=HOSTS)
    if show_demo and (df["is_demo"] == 1).any():
        st.warning("Showing SIMULATED demo incidents mixed with any real ones.")
    colors = {"High": "#d62728", "Watch": "#ff9f1c", "Low": "#2ca02c"}
    summ["color"] = summ["level"].map(colors)
    summ["size"] = 300 + summ["damaged_reports"] * 150
    st.map(summ, latitude="lat", longitude="lon", color="color", size="size")
    st.dataframe(
        summ[["zone_id", "trail", "zone_name", "level", "reports", "damaged_reports",
              "species_affected", "butterflies_at_risk", "top_species", "last_report"]],
        hide_index=True, use_container_width=True)
    st.caption("Damage is reported by users, not detected by the model. "
               "'Butterflies at risk' = butterflies recorded as hosts of the damaged plants.")
